"""The interactive 3D viewer: one standalone HTML file per boat.

    write_viewer(data, "reports/my-boat/viewer.html")            # plotly.js inlined: works offline
    write_viewer(data, "viewer.html", plotly="cdn")              # 30-70 kB, needs internet to open

`data` is the viewer data the engine writes next to the report as `viewer.json` (version 1). All lengths
are in metres in boat axes (x forward, y port, z up); displacements in mm; forces in kN; stresses in MPa.

    {"version": 1,
     "boat": {"name": "...", "rig": "...", "variant": "...", "file": "boats/x.yaml", "generated": "2026-10-27",
              "rigframe": "0.1.0", "estimates": 32, "inputs": 62},
     "yield_MPa": 240,
     "geos": {"A": {"nodes": [name, ...], "xyz": [[x, y, z], ...],
                    "heads": [{"mast": "main", "node": i}, ...],
                    "beams": [[i, j, "mast" | "spreader", label], ...],
                    "wires": [[i, j, label, size, MBL_kN], ...]}},
     "cases": [{"l": label, "s": solver, "g": geo key, "grp": optional group heading,
                "d": [[dx, dy, dz] per node],
                "b": [[peak stress, axial compression, M fore-aft kNm, M athwart kNm] per beam],
                "w": [[tension, wire stress] per wire]}]}

Labels are shown as text: the page escapes them, so nothing in a boat file can inject markup.
"""
from __future__ import annotations

import html
import json
import re
from importlib import resources
from pathlib import Path

PLOTLY_CDN = "https://cdn.jsdelivr.net/npm/plotly.js-dist-min@2.35.2/plotly.min.js"


def _template():
    try:
        return resources.files("rigframe").joinpath("viewer_template.html").read_text(encoding="utf-8")
    except (FileNotFoundError, ModuleNotFoundError):
        return (Path(__file__).with_name("viewer_template.html")).read_text(encoding="utf-8")


def _plotly_tag(mode):
    if mode == "inline":
        try:
            from plotly.offline import get_plotlyjs
        except ImportError:
            mode = "cdn"                                 # rigframe[viewer] not installed: fall back, and say so
            print("viewer: the plotly package isn't installed, so the viewer loads plotly.js from the internet")
        else:
            return "<script>" + get_plotlyjs().replace("</script", "<\\/script") + "</script>"
    return f'<script src="{PLOTLY_CDN}"></script>'


def write_viewer(data: dict, path, plotly: str = "inline", report_href: str | None = "REPORT.html") -> Path:
    """Write the standalone viewer. Returns its path."""
    b = data["boat"]
    name = b["name"] + (f" ({b['variant']})" if b.get("variant") else "")
    sub = [f"{html.escape(b.get('rig', '').capitalize())}. Generated by rigframe {b.get('rigframe', '')} from "
           f"<code>{html.escape(b.get('file', ''))}</code> on {html.escape(b.get('generated', ''))}."]
    if report_href:
        sub.append(f'<a href="{html.escape(report_href)}">Full report</a>.')
    n_est, n_in = b.get("estimates"), b.get("inputs")
    warn = ("An engineering estimate, not a rig survey."
            + (f" {n_est} of the {n_in} inputs are still estimates; the report lists them." if n_est else ""))
    payload = json.dumps(data, separators=(",", ":"), ensure_ascii=False).replace("</", "<\\/")
    fill = {"TITLE": html.escape(f"{name}: rig in 3D"),
            "H1": html.escape(f"{name}: stress and utilisation in 3D"),
            "SUB": " ".join(sub),
            "WARN": html.escape(warn),
            "PLOTLY": _plotly_tag(plotly),
            "DATA": payload}
    # One pass, so text from the boat file can never be read as another placeholder.
    page = re.sub(r"__(TITLE|H1|SUB|WARN|PLOTLY|DATA)__", lambda m: fill[m.group(1)], _template())
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(page, encoding="utf-8")
    return path


def main(argv=None):
    """python -m rigframe.viewer viewer.json out.html [--cdn]"""
    import sys
    args = argv if argv is not None else sys.argv[1:]
    if len(args) < 2:
        print(main.__doc__)
        return 2
    data = json.loads(Path(args[0]).read_text(encoding="utf-8"))
    out = write_viewer(data, args[1], plotly="cdn" if "--cdn" in args else "inline")
    print(f"wrote {out} ({out.stat().st_size / 1e3:.0f} kB, {len(data['cases'])} cases)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
